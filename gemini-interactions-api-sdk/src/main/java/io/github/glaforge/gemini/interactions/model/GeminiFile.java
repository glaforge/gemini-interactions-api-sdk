package io.github.glaforge.gemini.interactions.model;

import com.fasterxml.jackson.annotation.JsonAlias;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonInclude;
import io.github.glaforge.gemini.interactions.model.Content.AudioContent;
import io.github.glaforge.gemini.interactions.model.Content.AudioMediaProcessing;
import io.github.glaforge.gemini.interactions.model.Content.DocumentContent;
import io.github.glaforge.gemini.interactions.model.Content.DocumentMediaProcessing;
import io.github.glaforge.gemini.interactions.model.Content.ImageContent;
import io.github.glaforge.gemini.interactions.model.Content.MediaProcessing;
import io.github.glaforge.gemini.interactions.model.Content.Resolution;
import io.github.glaforge.gemini.interactions.model.Content.VideoContent;
import java.util.List;
import java.util.Map;

/**
 * Represents a file resource managed by the Gemini Files API ({@code /v1beta/files}).
 * <p>
 * Files uploaded via the Files API are stored for up to 48 hours and can be referenced by their
 * {@link #uri()} across multiple interaction turns, tool calls, and file-slicing requests without
 * re-uploading the underlying bytes.
 * </p>
 *
 * @param name           Immutable resource name of the file (e.g. {@code "files/abc-123"}).
 * @param displayName    Optional human-readable display name for the file.
 * @param mimeType       MIME type of the file (e.g. {@code "application/pdf"}, {@code "video/mp4"}).
 * @param sizeBytes      Size of the file in bytes.
 * @param createTime     RFC 3339 timestamp of when the file was created.
 * @param updateTime     RFC 3339 timestamp of when the file was last updated.
 * @param expirationTime RFC 3339 timestamp of when the file will be deleted, if scheduled to expire.
 * @param sha256Hash     Base64-encoded SHA-256 hash of the uploaded bytes.
 * @param uri            The URI of the file, used when referencing the file in interaction content blocks.
 * @param downloadUri    The download URI of the file (applicable to model-generated files).
 * @param state          Processing state of the file ({@link State}).
 * @param source         Source of the file ({@link Source}).
 * @param error          Error status if file processing failed.
 * @param videoMetadata  Optional metadata for a video file.
 */
@JsonInclude(JsonInclude.Include.NON_NULL)
@JsonIgnoreProperties(ignoreUnknown = true)
public record GeminiFile(
    String name,
    @JsonAlias("display_name") String displayName,
    @JsonAlias("mime_type") String mimeType,
    @JsonAlias("size_bytes") Long sizeBytes,
    @JsonAlias("create_time") String createTime,
    @JsonAlias("update_time") String updateTime,
    @JsonAlias("expiration_time") String expirationTime,
    @JsonAlias("sha256_hash") String sha256Hash,
    String uri,
    @JsonAlias("download_uri") String downloadUri,
    State state,
    Source source,
    FileError error,
    @JsonAlias("video_metadata") VideoMetadata videoMetadata
) {

    /**
     * Processing lifecycle states of a {@link GeminiFile}.
     */
    public enum State {
        /** Default unspecified state. */
        STATE_UNSPECIFIED,
        /** File is being processed and cannot be used for inference yet. */
        PROCESSING,
        /** File is processed and ready for inference. */
        ACTIVE,
        /** File failed processing. */
        FAILED
    }

    /**
     * Origin source of a {@link GeminiFile}.
     */
    public enum Source {
        /** Unspecified source. */
        SOURCE_UNSPECIFIED,
        /** File uploaded by the user. */
        UPLOADED,
        /** File generated by Google. */
        GENERATED,
        /** File registered from Google Cloud Storage. */
        REGISTERED
    }

    /**
     * Metadata specific to video files.
     *
     * @param videoDuration Duration of the video as a protobuf Duration string (e.g. {@code "3.5s"}).
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    @JsonIgnoreProperties(ignoreUnknown = true)
    public record VideoMetadata(
        @JsonAlias("video_duration") String videoDuration
    ) {}

    /**
     * Error details returned when a {@link GeminiFile} fails processing (maps to {@code google.rpc.Status}).
     *
     * @param code    The gRPC status code.
     * @param message Developer-facing error message.
     * @param details Optional list of additional error detail payloads.
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    @JsonIgnoreProperties(ignoreUnknown = true)
    public record FileError(
        Integer code,
        String message,
        List<Map<String, Object>> details
    ) {}

    /**
     * Returns true if the file is in the {@link State#ACTIVE} state and ready for use in interactions.
     *
     * @return true if {@code state == State.ACTIVE}.
     */
    public boolean isActive() {
        return state == State.ACTIVE;
    }

    /**
     * Returns true if the file is currently in the {@link State#PROCESSING} state.
     *
     * @return true if {@code state == State.PROCESSING}.
     */
    public boolean isProcessing() {
        return state == State.PROCESSING;
    }

    /**
     * Returns true if file processing failed ({@link State#FAILED}).
     *
     * @return true if {@code state == State.FAILED}.
     */
    public boolean isFailed() {
        return state == State.FAILED;
    }

    /**
     * Converts this file into a {@link DocumentContent} block referencing its {@link #uri()} and {@link #mimeType()}.
     *
     * @return A {@link DocumentContent} referencing this file.
     */
    public DocumentContent toDocumentContent() {
        return new DocumentContent(uri, mimeType);
    }

    /**
     * Converts this file into a {@link DocumentContent} block with resolution and processing configuration.
     *
     * @param resolution Optional media resolution.
     * @param processing Optional document processing configuration.
     * @return A {@link DocumentContent} referencing this file.
     */
    public DocumentContent toDocumentContent(Resolution resolution, DocumentProcessingConfiguration processing) {
        return new DocumentContent(uri, mimeType, resolution, processing);
    }

    /**
     * Converts this file into a {@link DocumentContent} block with resolution and custom document processing options.
     *
     * @param resolution Optional media resolution.
     * @param processing Optional document media processing configuration (e.g. page or spreadsheet slicing).
     * @return A {@link DocumentContent} referencing this file.
     */
    public DocumentContent toDocumentContent(Resolution resolution, DocumentMediaProcessing processing) {
        return new DocumentContent(uri, mimeType, resolution, processing);
    }

    /**
     * Converts this file into an {@link ImageContent} block referencing its {@link #uri()} and {@link #mimeType()}.
     *
     * @return An {@link ImageContent} referencing this file.
     */
    public ImageContent toImageContent() {
        return new ImageContent(uri, mimeType);
    }

    /**
     * Converts this file into an {@link ImageContent} block with a specified resolution.
     *
     * @param resolution Optional media resolution.
     * @return An {@link ImageContent} referencing this file.
     */
    public ImageContent toImageContent(Resolution resolution) {
        return new ImageContent(uri, mimeType, resolution);
    }

    /**
     * Converts this file into an {@link AudioContent} block referencing its {@link #uri()} and {@link #mimeType()}.
     *
     * @return An {@link AudioContent} referencing this file.
     */
    public AudioContent toAudioContent() {
        return new AudioContent(uri, mimeType);
    }

    /**
     * Converts this file into an {@link AudioContent} block with an audio processing configuration.
     *
     * @param processing Optional audio processing configuration.
     * @return An {@link AudioContent} referencing this file.
     */
    public AudioContent toAudioContent(AudioProcessingConfiguration processing) {
        return new AudioContent(uri, mimeType, processing);
    }

    /**
     * Converts this file into an {@link AudioContent} block with custom audio processing options.
     *
     * @param processing Optional audio media processing configuration (e.g. time interval slicing).
     * @return An {@link AudioContent} referencing this file.
     */
    public AudioContent toAudioContent(AudioMediaProcessing processing) {
        return new AudioContent(uri, mimeType, processing);
    }

    /**
     * Converts this file into a {@link VideoContent} block referencing its {@link #uri()} and {@link #mimeType()}.
     *
     * @return A {@link VideoContent} referencing this file.
     */
    public VideoContent toVideoContent() {
        return new VideoContent("video", null, uri, mimeType, null);
    }

    /**
     * Converts this file into a {@link VideoContent} block with resolution and media processing configuration.
     *
     * @param resolution Optional media resolution.
     * @param processing Optional media processing configuration (e.g. {@code "agentic"} or static slicing).
     * @return A {@link VideoContent} referencing this file.
     */
    public VideoContent toVideoContent(Resolution resolution, MediaProcessingConfiguration processing) {
        return new VideoContent("video", null, uri, mimeType, resolution, processing);
    }

    /**
     * Converts this file into a {@link VideoContent} block with resolution and custom media processing options.
     *
     * @param resolution Optional media resolution.
     * @param processing Optional media processing configuration (e.g. time interval, FPS, content layers).
     * @return A {@link VideoContent} referencing this file.
     */
    public VideoContent toVideoContent(Resolution resolution, MediaProcessing processing) {
        return new VideoContent("video", null, uri, mimeType, resolution, processing);
    }
}
